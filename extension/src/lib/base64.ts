// Shared base64 <-> binary helpers. Used by downloads.ts (blob -> data URL,
// for chrome.downloads.download) and background/index.ts (base64 -> Blob,
// for blob: sources whose bytes were read in-page and passed back as base64
// since a page-scoped blob: URL isn't fetchable from the extension background).

export function arrayBufferToBase64(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  const chunkSize = 0x8000;
  let binary = "";
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}

export function base64ToBlob(base64: string, mime: string): Blob {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return new Blob([bytes], { type: mime });
}
